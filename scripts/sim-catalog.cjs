function buildCatalog(count = 150) {
  const out = []
  for (let i = 0; i < count; i++) {
    const src = BASE[i % BASE.length]
    const [name, unit, cost, price, stock, min] = src
    const suffix = i >= BASE.length ? ` (تشكيلة ${Math.floor(i / BASE.length) + 1})` : ''
    // decimal prices for some
    const costN = i % 7 === 0 ? Number((cost + 0.25).toFixed(2)) : cost
    const priceN = i % 5 === 0 ? Number((price + 0.5).toFixed(2)) : price
    out.push({
      name_ar: name + suffix,
      name_en: `Item ${i + 1}`,
      barcode: `622${String(1000000000 + i).slice(-10)}`,
      unit,
      costPrice: costN,
      retailPrice: priceN,
      wholesalePrice: Number((priceN * 0.92).toFixed(2)),
      stockQty: stock + (i % 11),
      minimumStock: min,
    })
  }
  return out
}

